// Generates src/data/talents.generated.ts from a talent rule note + scripts/talent-supplement.json.
// Usage: npm run gen:talents -- <path/to/Talentfertigkeiten.md>
//    or: DSA_TALENT_NOTE=<path/to/Talentfertigkeiten.md> npm run gen:talents
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const usage = `Usage: npm run gen:talents -- <path/to/Talentfertigkeiten.md>
   or: DSA_TALENT_NOTE=<path/to/Talentfertigkeiten.md> npm run gen:talents

The note must be a Markdown file with one "# <Gruppe>" heading per talent group
(Körpertalente, Gesellschaftstalente, Naturtalente, Wissenstalente) and table rows
whose second column holds the attributes, e.g. "MU/KL/IN".`;
const notePath = process.argv[2] ?? process.env.DSA_TALENT_NOTE;
if (!notePath) {
  console.error(usage);
  process.exit(1);
}
const resolvedNote = path.resolve(notePath);
if (!fs.existsSync(resolvedNote) || !fs.statSync(resolvedNote).isFile()) {
  console.error(`Talent note not found or not a file: ${resolvedNote}\n\n${usage}`);
  process.exit(1);
}
const note = fs.readFileSync(resolvedNote, "utf8");
const supplement = JSON.parse(fs.readFileSync(path.join(here, "talent-supplement.json"), "utf8"));

const groupNames = { Körpertalente: "Körper", Gesellschaftstalente: "Gesellschaft", Naturtalente: "Natur", Wissenstalente: "Wissen" };
const order = ["Körper", "Gesellschaft", "Natur", "Wissen", "Handwerk"];
const groups = Object.fromEntries(order.map((g) => [g, []]));

let current = null;
for (const line of note.split("\n")) {
  const h = line.match(/^#\s+(.+?)\s*$/);
  if (h) { current = groupNames[h[1]] ?? null; continue; }
  if (!current || !line.startsWith("|")) continue;
  const cells = line.split("|").slice(1, -1).map((c) => c.trim());
  const m = cells[1]?.match(/^([A-Z]{2})\/([A-Z]{2})\/([A-Z]{2})$/);
  if (!m) continue;
  groups[current].push({ name: cells[0].replace(/\s+/g, " "), attrs: [m[1], m[2], m[3]], encumbrance: cells[2], source: "vault" });
}
for (const [g, list] of Object.entries(supplement)) {
  if (g.startsWith("_")) continue;
  for (const t of list) groups[g].push({ ...t, encumbrance: "", source: "dsa5-core" });
}
const collator = new Intl.Collator("de");
const out = [];
for (const g of order) {
  groups[g].sort((a, b) => collator.compare(a.name, b.name));
  for (const t of groups[g]) out.push({ name: t.name, group: g, attrs: t.attrs, belastung: t.encumbrance, source: t.source });
}
const ts = `// GENERATED by scripts/gen-talents.mjs - do not edit by hand.
// Order = Heldenschmiede key order (group order Körper, Gesellschaft, Natur, Wissen, Handwerk; alphabetical inside a group).
import type { TalentDef } from "../engine/types";

export const TALENTS: TalentDef[] = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync(path.join(root, "src/data/talents.generated.ts"), ts);
console.log(`wrote ${out.length} talents`);
